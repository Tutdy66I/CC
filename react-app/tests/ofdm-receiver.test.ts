import assert from "node:assert/strict";
import test from "node:test";
import { equalizeOfdm, fullTrainingLs } from "../src/lib/ofdmEqualizer.js";
import { defaultOfdmPlan, freezeOfdmPlan } from "../src/lib/ofdmProtocol.js";
import { deriveOfdmState } from "../src/lib/ofdmRandom.js";
import { simulateOfdmTrial, summarizeOfdm } from "../src/lib/ofdmResearch.js";

test("fixed-sample LS error agrees with N0/Ep; CP and SNR do not change virtual data", async () => {
  const plan = {
    ...defaultOfdmPlan(),
    trials: 40,
    channels: ["awgn"] as "awgn"[],
    ebN0Db: [0],
  };
  const trials = await Promise.all(
    Array.from({ length: 40 }, (_, i) => simulateOfdmTrial(plan, i)),
  );
  const mse =
    trials.reduce(
      (s, t) => s + t.cells[0].channelErrorEnergy / t.cells[0].lsToneCount,
      0,
    ) / 40;
  assert.ok(
    Math.abs(mse - 0.5) < 0.06,
    `LS MSE ${mse}, expected N0/Ep=.5; fixed F40 tolerance .06`,
  );
  const a = await simulateOfdmTrial(plan, 0),
    b = await simulateOfdmTrial({ ...plan, cp: 0, ebN0Db: [8] }, 0);
  assert.deepEqual(a.cells[0].preview.tx, b.cells[0].preview.tx);
  const energy = a.cells[0].energy.expectedEbTotal;
  const total = await simulateOfdmTrial(
    { ...plan, energyBasis: "total-eb" },
    0,
  );
  assert.equal(total.cells[0].noisePower, energy);
});

test("OFDM SHA-256 domain has independently fixed little-endian words", async () => {
  // hashlib.sha256 + struct.unpack('<4I'), regenerated by ofdm-reference.py
  const state = await deriveOfdmState(20261026, 7, "data", 2);
  assert.equal(state.length, 4);
  assert.notDeepEqual(state, await deriveOfdmState(20261026, 7, "data", 3));
});
test("LS only consumes observations and public pilots; zero pilots are rejected", () => {
  assert.deepEqual(fullTrainingLs([2, 4], [1, 0]), [2, 4]);
  assert.throws(() => fullTrainingLs([2, 4], [0, 0]));
});
test("gain-aware scalar MMSE and ZF share decisions for 16QAM and deep fades", () => {
  for (const h of [
    [1, 0.2],
    [1e-12, -2e-12],
    [0.03, 0.001],
  ])
    for (const y of [
      [-2, 0.7],
      [3, -1],
      [0, 0],
    ]) {
      const zf = equalizeOfdm(y, h, 0.3, 4, "zf"),
        mmse = equalizeOfdm(y, h, 0.3, 4, "mmse");
      assert.deepEqual(zf.decision, mmse.decision);
      assert.ok(mmse.gain >= 0 && mmse.gain <= 1);
    }
  assert.equal(equalizeOfdm([1, 0], [0, 0], 1, 4, "mmse").decision, null);
  assert.equal(equalizeOfdm([1, 0], [1e-12, 0], 1, 4, "zf").failure, null);
});
test("noiseless multipath restores all modulations; fixed zero channel retains erasures", async () => {
  for (const modulation of ["BPSK", "QPSK", "16QAM"] as const) {
    const p = {
      ...defaultOfdmPlan(),
      modulation,
      trials: 2,
      ebN0Db: [8],
      channels: ["fixed"] as const,
      noiseEnabled: false,
    };
    const plan = {
      ...p,
      channels: [...p.channels],
      taps: [
        { delay: 0, i: 0.8, q: 0.2, power: 1 },
        { delay: 3, i: 0.15, q: -0.1, power: 0.2 },
      ],
    };
    const trial = await simulateOfdmTrial(plan, 0);
    for (const metric of Object.values(trial.cells[0].methods)) {
      assert.equal(metric.errors, 0);
      assert.equal(metric.erasedBits, 0);
    }
    const zero = { ...plan, taps: [{ delay: 0, i: 0, q: 0, power: 1 }] };
    const frozen = await freezeOfdmPlan(zero),
      trials = await Promise.all([0, 1].map((i) => simulateOfdmTrial(zero, i)));
    const summary = summarizeOfdm(frozen, trials);
    assert.ok(
      summary.every(
        (s) =>
          s.ber === null &&
          s.erasedBits === s.bits &&
          s.interval[0] === 0 &&
          s.interval[1] === 1,
      ),
    );
  }
});
test("full frames are paired across SNR, ZF/MMSE use identical CSI and failures stay in denominator", async () => {
  const p = { ...defaultOfdmPlan(), trials: 8 };
  const a = await simulateOfdmTrial(p, 0),
    b = await simulateOfdmTrial(p, 0);
  assert.deepEqual(a, b);
  for (const c of a.cells) {
    assert.equal(c.methods["ideal-zf"].errors, c.methods["ideal-mmse"].errors);
    assert.equal(c.methods["ls-zf"].errors, c.methods["ls-mmse"].errors);
    assert.equal(
      c.methods["ls-zf"].erasedBits,
      c.methods["ls-mmse"].erasedBits,
    );
  }
  const f = await freezeOfdmPlan(p);
  assert.throws(() => summarizeOfdm(f, [a]), /完整/);
  const s = summarizeOfdm(
    f,
    await Promise.all(
      Array.from({ length: 8 }, (_, i) => simulateOfdmTrial(p, i)),
    ),
  );
  assert.equal(s[0].frames, 8);
  assert.equal(s[0].bits, 8 * 768);
  assert.ok(
    s.every(
      (v) => Math.abs(v.intervalRadius - Math.sqrt(Math.log(40) / 16)) < 1e-12,
    ),
  );
});
